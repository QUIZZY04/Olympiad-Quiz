// Injection loop
let totalInjected = 0;

for (let ch = 1; ch <= 16; ch++) {
  const chId = `ch${ch}`;
  const chRegex = new RegExp(`(<section id="${chId}"[\\s\\S]*?)(<!-- CBQ -->)`);
  const match = html.match(chRegex);
  
  if (!match) {
    console.error(`ERROR: Section ${chId} with <!-- CBQ --> not found!`);
    process.exit(1);
  }

  const questions = INJECTIONS[ch];
  if (!questions || questions.length === 0) {
    console.log(`No questions to inject for Ch ${ch}`);
    continue;
  }

  let cardsHtml = '';
  for (const q of questions) {
    cardsHtml += generateCard(ch, q.qNum, q.qNumDev, q.text, q.marks, q.answer, q.rubric);
    totalInjected++;
  }

  // Replace section: add cardsHtml before <!-- CBQ -->
  const updatedSection = match[1] + cardsHtml + '  ' + match[2];
  html = html.replace(chRegex, updatedSection);
  console.log(`Ch ${ch}: Injected ${questions.length} questions.`);
}

console.log(`\nTotal questions injected: ${totalInjected}`);

// Write updated HTML
fs.writeFileSync(FILE_PATH, html, 'utf8');
